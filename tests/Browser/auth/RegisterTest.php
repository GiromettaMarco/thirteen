<?php

it('may register a new user and require email verification to proceed')
    ->visit('/register')
    ->on()
    ->mobile()
    ->assertSee('Create an account')
    ->fill('name', 'John Smith')
    ->fill('email', 'jhonsmith@example.com')
    ->fill('password', 'password')
    ->fill('password_confirmation', 'password')
    ->click('Create account')
    ->assertTitleContains('Email verification');

it('may throttle register submissions when email is already taken')
    ->visit('/register')
    ->on()
    ->mobile()
    ->assertSee('Create an account')
    ->fill('name', 'John Smith')
    ->fill('email', 'test@example.com')
    ->fill('password', 'password')
    ->fill('password_confirmation', 'password')
    ->click('Create account')
    ->assertSee('This email ha already been taken.')
    ->click('Create account')
    ->assertSee('This email ha already been taken.')
    ->click('Create account')
    ->assertSee('Too many attempts.');

it('may throttle successful register submissions')
    ->visit('/register')
    ->on()
    ->mobile()
    ->assertSee('Create an account')
    ->fill('name', 'John Smith')
    ->fill('email', 'jhonsmith@example.com')
    ->fill('password', 'password')
    ->fill('password_confirmation', 'password')
    ->click('Create account')
    ->assertSee('Verify email')
    ->click('Sign Out')
    ->assertSee('Welcome to Thirteen')
    ->click("Let's get started!")
    ->assertSee('Log in to your account')
    ->click('Sign Up')
    ->assertSee('Create an account')
    ->fill('name', 'Jack Brown')
    ->fill('email', 'jackbrown@example.com')
    ->fill('password', 'password')
    ->fill('password_confirmation', 'password')
    ->click('Create account')
    ->assertSee('Too many attempts.');
